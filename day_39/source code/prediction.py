import os
import csv
from ultralytics import YOLO
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_PATH = os.path.join(BASE_DIR, "models", "best.pt")
IMAGE_DIR = os.path.join(BASE_DIR, "unseen_images")
OUTPUT_DIR = os.path.join(BASE_DIR, "predictions", "shoe_predictions")
REPORT_DIR = os.path.join(BASE_DIR, "error_analysis")
os.makedirs(OUTPUT_DIR, exist_ok=True)
os.makedirs(REPORT_DIR, exist_ok=True)
model = YOLO(MODEL_PATH)
image_files = [f for f in os.listdir(IMAGE_DIR) if f.lower().endswith((".jpg", ".jpeg", ".png"))]
image_files.sort()
if len(image_files) < 20:
    print(f"Warning: Only {len(image_files)} unseen images found.")
else:
    image_files = image_files[:20]
results = []
for index, image_name in enumerate(image_files, 1):
    image_path = os.path.join(IMAGE_DIR, image_name)
    prediction = model.predict(source=image_path, conf=0.25, imgsz=512, save=False, verbose=False)[0]
    output_path = os.path.join(OUTPUT_DIR, image_name)
    prediction.save(filename=output_path)
    detections = len(prediction.boxes)
    confidences = [float(conf) for conf in prediction.boxes.conf] if detections > 0 else []
    average_confidence = sum(confidences) / len(confidences) if confidences else 0
    results.append({"Image": image_name, "Detections": detections, "Average Confidence": round(average_confidence, 4)})
    print(f"{index:02d}/20 | {image_name} | Detections: {detections} | Avg Confidence: {average_confidence:.3f}")
csv_path = os.path.join(REPORT_DIR, "unseen_predictions.csv")
with open(csv_path, "w", newline="", encoding="utf-8") as file:
    writer = csv.DictWriter(file, fieldnames=["Image", "Detections", "Average Confidence"])
    writer.writeheader()
    writer.writerows(results)
total_detections = sum(row["Detections"] for row in results)
images_with_detection = sum(1 for row in results if row["Detections"] > 0)
images_without_detection = sum(1 for row in results if row["Detections"] == 0)
all_confidences = [float(conf) for row in results for conf in [row["Average Confidence"]] if row["Detections"] > 0]
overall_confidence = sum(all_confidences) / len(all_confidences) if all_confidences else 0
report_path = os.path.join(REPORT_DIR, "unseen_evaluation_report.txt")
with open(report_path, "w", encoding="utf-8") as file:
    file.write("DAY 39 MODEL TESTING REPORT\n")
    file.write("===========================\n\n")
    file.write(f"Unseen Images Tested: {len(image_files)}\n")
    file.write(f"Images With Detections: {images_with_detection}\n")
    file.write(f"Images Without Detections: {images_without_detection}\n")
    file.write(f"Total Predicted Objects: {total_detections}\n")
    file.write(f"Average Detection Confidence: {overall_confidence:.4f}\n\n")
    file.write("MODEL METRICS\n-------------\n")
    file.write("Precision: Requires ground-truth annotations (not computed - see note below)\n")
    file.write("Recall: Requires ground-truth annotations (not computed - see note below)\n")
    file.write("mAP@50: Requires ground-truth annotations (not computed - see note below)\n")
    file.write("mAP@50-95: Requires ground-truth annotations (not computed - see note below)\n\n")
    file.write("Note: These unseen images have no ground-truth label files, so Precision/Recall/mAP cannot be calculated for this batch directly.\n")
    file.write("The model metrics shown in the training/validation results come from the labeled validation/test split and are not metrics for this unseen-image batch.\n\n")
    file.write("MANUAL ERROR ANALYSIS (based on visual review of prediction images)\n---------------------------------------------------------------------\n\n")
    file.write("The prediction images generated by YOLO were visually inspected for duplicate boxes, false positives, missed detections, severe over-detection, and low-confidence predictions.\n\n")
    file.write("1. DUPLICATE / OVERLAPPING BOXES ON THE SAME SHOE\n")
    file.write("The model sometimes draws multiple overlapping boxes on one shoe instead of producing one clean bounding box.\n")
    file.write("- catkin-childrens-shoe-1728294: one baby shoe receives 3 overlapping boxes.\n")
    file.write("- e_stamm-shoes-4655404: the same shoe receives 2 overlapping boxes.\n")
    file.write("- usa-reiseblogger-running-5370071: the right shoe receives 2 overlapping boxes.\n\n")
    file.write("2. FALSE POSITIVES ON TEXT / NON-SHOE OBJECTS\n")
    file.write("The model sometimes detects regions that are not shoes but contain similar shapes, textures, or patterns.\n")
    file.write("- e_stamm-shoes-4655404: letters in the word 'BOOST' are incorrectly detected as shoes.\n")
    file.write("- planet_fox-ball-8048205: part of a soccer ball is incorrectly detected as a shoe.\n\n")
    file.write("3. MISSED DETECTIONS\n")
    file.write("The model sometimes detects only one object when two or more shoes are present.\n")
    file.write("- spiralni-shoe-4814211: two hiking boots are present but only one bounding box is produced.\n")
    file.write("- ddcreativohn-shoes-3967944: two hanging shoes are present but only one is detected.\n\n")
    file.write("4. SEVERE OVER-DETECTION ON CLUTTERED / REPETITIVE SCENES\n")
    file.write("- ivabalk-bowling-shoes-2779989: the model produces 105 detections on one image containing many similar bowling shoes, with numerous duplicate and overlapping boxes.\n\n")
    file.write("5. LOW CONFIDENCE ON PARTIAL / OCCLUDED / TEXTURED SHOES\n")
    file.write("Some correct detections have relatively low confidence when shoes are partially visible, heavily textured, worn, cropped, or photographed from unusual angles.\n")
    file.write("- ddcreativohn-shoes-3967944: approximately 0.43 confidence.\n")
    file.write("- spiralni-shoe-4814211: approximately 0.46 confidence.\n")
    file.write("- un-perfekt-sports-shoes-3994967: approximately 0.43 average confidence.\n\n")
    file.write("WHERE THE MODEL PERFORMS WELL\n------------------------------\n")
    file.write("The model performs better on clearly visible shoes with simple backgrounds such as grass, pavement, studio backgrounds, and clear individual boot images.\n")
    file.write("- homar-converse-1935026: 0.8542 average confidence.\n")
    file.write("- rojesh55-sport-7047874: 0.8212 average confidence.\n")
    file.write("- active-boots image: strong individual boot detections.\n")
    file.write("- wal_172619-pedestrian: several shoes detected across different people.\n\n")
    file.write("IMAGE RESULTS\n-------------\n")
    for row in results:
        file.write(f"{row['Image']} | Detections: {row['Detections']} | Average Confidence: {row['Average Confidence']:.4f}\n")
    file.write("\nSUGGESTED 5 DIFFICULT EXAMPLES FOR README\n-------------------------------------------\n")
    file.write("1. ivabalk-bowling-shoes-2779989 - severe over-detection in a dense shelf of repetitive shoes.\n")
    file.write("2. spiralni-shoe-4814211 - two boots treated as one object.\n")
    file.write("3. e_stamm-shoes-4655404 - false positives on 'BOOST' text.\n")
    file.write("4. ddcreativohn-shoes-3967944 - one of two hanging shoes is missed.\n")
    file.write("5. catkin-childrens-shoe-1728294 - multiple overlapping boxes on one close-up shoe.\n\n")
    file.write("CONCLUSION\n----------\n")
    file.write("The unseen-image testing shows that the model can detect shoes in different real-world scenes, but visual inspection reveals duplicate detections, false positives, missed objects, over-detection in cluttered scenes, and lower confidence for unusual viewpoints. Since the unseen images have no ground-truth annotations, this batch should be considered a qualitative/manual evaluation rather than a formal Precision, Recall, or mAP evaluation.\n")
print("\nTesting completed.")
print(f"Images tested: {len(image_files)}")
print(f"Total detections: {total_detections}")
print(f"Images with detections: {images_with_detection}")
print(f"Images without detections: {images_without_detection}")
print(f"Predictions saved to: {OUTPUT_DIR}")
print(f"CSV report saved to: {csv_path}")
print(f"Evaluation report saved to: {report_path}")